# config/writer.py — Targeted in-place updates to config.yaml
#
# patch_config_yaml(path, **kwargs) — load → patch → dump without touching unrelated sections.
# PyYAML round-trip does not preserve comments; that is acceptable for operator-edited config.
# No Qt. No network I/O.

from __future__ import annotations

import logging
from dataclasses import asdict
from pathlib import Path

import yaml

from config.settings import AppSettings
from core.atomic_write import write_text_atomic

logger = logging.getLogger(__name__)

# Prepended to every generated config.yaml. Comments survive safe_load but are
# lost on the next patch_config_yaml round-trip; that is acceptable for a file
# the installer owns and operators rarely hand-edit.
_CONFIG_HEADER = (
    "# KH PTZ Control — config.yaml\n"
    "# Generated by KHPTZ setup. Safe to hand-edit only when no session is live.\n"
    "# Do not edit during a live session.\n"
    "\n"
)


def write_full_config(
    settings: AppSettings, path: Path, *, mode: "int | None" = None
) -> None:
    """Serialise a complete *settings* tree to *path* as YAML, atomically.

    Inverse of ``config.loader.load_config``: every field the loader reads is
    preserved across a write→load round-trip. Used by the setup wizard to
    create config.yaml from scratch (``patch_config_yaml`` can only edit an
    existing file).

    Uses ``yaml.safe_dump``, which raises rather than emit ``!!python/...``
    tags, so no executable object markers can ever reach config.yaml. *mode*,
    when given, sets the destination permissions (e.g. 0o640 so the service
    user can read it). Ownership (chown) is the provisioning layer's job.
    """
    body = yaml.safe_dump(
        asdict(settings),
        default_flow_style=False,
        sort_keys=False,
        allow_unicode=True,
    )
    write_text_atomic(path, _CONFIG_HEADER + body, mode=mode)
    logger.info("config.yaml written in full: %s", path)


def patch_config_yaml(
    path: Path,
    *,
    cam_index: int | None = None,
    cam_ip: str | None = None,
    cam_visca_id: str | None = None,
    atem_ip: str | None = None,
    atem_pip_nudge: "dict | None" = None,
) -> None:
    """Apply targeted field updates to *path* (config.yaml) in-place.

    Parameters
    ----------
    path:
        Absolute path to config.yaml.
    cam_index:
        0-based camera index (0 = cam1, 1 = cam2). Required when ``cam_ip`` or
        ``cam_visca_id`` is supplied.
    cam_ip:
        New IPv4 address for ``cameras[cam_index].ip``.
    cam_visca_id:
        New VISCA hex byte for ``cameras[cam_index].visca_id``.
    atem_ip:
        New IPv4 address for ``atem.ip``.

    Raises
    ------
    FileNotFoundError
        If *path* does not exist.
    IndexError
        If *cam_index* is out of range for the cameras list in the file.
    yaml.YAMLError
        If the file contains invalid YAML.
    OSError
        If the file cannot be written.
    """
    raw: dict = yaml.safe_load(path.read_text(encoding="utf-8")) or {}

    if cam_ip is not None or cam_visca_id is not None:
        if cam_index is None:
            raise ValueError("cam_index is required when updating camera fields")
        cameras = raw.get("cameras")
        if not isinstance(cameras, list) or cam_index >= len(cameras):
            raise IndexError(
                f"cameras[{cam_index}] does not exist in {path}"
            )
        if not isinstance(cameras[cam_index], dict):
            raise TypeError(
                f"cameras[{cam_index}] is not a dict in {path}"
            )
        if cam_ip is not None:
            cameras[cam_index]["ip"] = cam_ip
        if cam_visca_id is not None:
            cameras[cam_index]["visca_id"] = cam_visca_id

    if atem_ip is not None:
        raw.setdefault("atem", {})["ip"] = atem_ip

    if atem_pip_nudge is not None:
        raw.setdefault("atem", {}).setdefault("pip_nudge", {}).update(atem_pip_nudge)

    write_text_atomic(
        path,
        yaml.dump(raw, allow_unicode=True, default_flow_style=False, sort_keys=False),
    )
    logger.info("config.yaml patched: %s", path)
